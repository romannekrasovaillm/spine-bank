//! Пользовательская диагностика в обход UI: единый канал «предупреждение»,
//! маршрут которого зависит от режима интерфейса.
//!
//! Зачем модуль существует (инцидент 2026-10-14 в AI/ML-редакции,
//! spine-aiml 0.5.4): библиотечный код прогона харнессов (`harness`) печатал
//! предупреждения голым `eprintln!`. В TUI-режиме процесс держит терминал в
//! alternate screen, а ratatui перерисовывает только ячейки, изменившиеся в
//! ЕГО буферной модели: чужая строка в stderr ложится на экран в произвольной
//! позиции курсора, скроллит alternate screen — и модель буфера об этом не
//! узнаёт никогда. След — «утечка UI»: сдвинутые строки состояния, обрывки
//! текста поверх панелей и полосы фона терминала там, где кадр считается уже
//! нарисованным. Поэтому из кода, способного сработать внутри TUI-сеанса
//! (агентный цикл, фоновые задачи, инструменты), печатать в stdout/stderr
//! напрямую НЕЛЬЗЯ — только сюда.
//!
//! Маршруты:
//! - TUI-режим (после [`enter_tui_mode`]) — `tracing::warn!`: в интерактивном
//!   режиме tracing пишется в `<state_dir>/arch-be.log` (см. `cli::init_tracing`),
//!   экран не трогаем;
//! - прочие режимы (CLI, headless) — `eprintln!`, как раньше.
//!
//! Модуль — листовой: зависимостей от остального крейта нет и не появится.

use std::sync::atomic::{AtomicBool, Ordering};

/// «TUI владеет экраном». Односторонняя защёлка: выставляется один раз при
/// входе в интерактивный режим (`tui::run`) и не снимается до конца
/// процесса — режим по ходу сеанса не меняется.
static TUI_OWNS_SCREEN: AtomicBool = AtomicBool::new(false);

/// Отмечает, что процесс вошёл в TUI-режим и экран больше никому не
/// принадлежит. Идемпотентно; вызывается один раз из `tui::run`.
pub(crate) fn enter_tui_mode() {
    TUI_OWNS_SCREEN.store(true, Ordering::Relaxed);
}

/// TUI держит alternate screen: любая прямая запись в stdout/stderr ломает
/// кадр (см. шапку модуля).
//
// allow(dead_code): единственный вызывающий — `warn` выше (см. его комментарий).
#[allow(dead_code)]
pub(crate) fn tui_owns_screen() -> bool {
    TUI_OWNS_SCREEN.load(Ordering::Relaxed)
}

/// Предупреждение пользователю из библиотечного кода, способного сработать
/// внутри TUI-сеанса. Не печатайте из такого кода сами — см. шапку модуля.
//
// Потребителей в этой редакции пока нет (все TUI-достижимые пути уже молчат
// или возвращают Result); канал — стандарт для будущих предупреждений,
// портирован вместе с эталоном spine-aiml 0.5.4.
#[allow(dead_code)]
pub(crate) fn warn(msg: &str) {
    if tui_owns_screen() {
        // В TUI tracing уходит в лог-файл сеанса (cli::init_tracing), экран
        // не затрагивается. Пользовательски значимые флаги дополнительно
        // попадают в результат инструмента — этот канал для фоновой
        // диагностики.
        tracing::warn!("{msg}");
    } else {
        eprintln!("{msg}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tui_mode_latches_on_and_warn_works_in_both_modes() {
        // Защёлка односторонняя и общая на процесс: параллельные тесты могли
        // уже вызвать enter_tui_mode, поэтому проверяются только пост-условия,
        // а не начальное состояние флага.
        warn("проверка маршрута до входа (CLI или уже-TUI)");
        enter_tui_mode();
        assert!(tui_owns_screen(), "после входа — TUI-режим");
        enter_tui_mode();
        assert!(tui_owns_screen(), "повторный вход идемпотентен");
        // Дымовой прогон TUI-маршрута: канал обязан молча работать и без
        // подписчика tracing (тестовый процесс его не ставит).
        warn("проверка TUI-маршрута");
    }
}
