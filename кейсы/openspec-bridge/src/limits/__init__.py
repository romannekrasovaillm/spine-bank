"""Движок лимитов (CMP-002): проверка суммы до побочного эффекта."""

LIMIT_MINOR = 1_000_000_00  # лимит операции, копейки


def check_limits(amount_minor: int) -> str:
    """Причина отказа либо пустая строка; суммы — целые копейки (AD-2)."""
    if amount_minor > LIMIT_MINOR:
        return "превышен лимит операции"
    return ""
