"""Заготовка фейка: счётчик эффектов, с которого начинается ваш фейк.

Фейк считает то, что проверяет ваш инвариант: сколько раз обратились к внешней
системе, сколько действий создали, сколько лимита списали. Ни сети, ни сна —
детерминированный прогон за миллисекунды.

Замените класс ниже своим фейком: назовите его по предметной области
(`FakePaymentGateway`, `FakeNotificationSink`, ...) и добавьте методы, которые
вызывает ваша настоящая точка входа.
"""


class FakeEffects:
    """Счётчик побочных эффектов — минимальная заготовка под ваш фейк."""

    def __init__(self) -> None:
        self.effects: list[tuple] = []

    def record(self, *effect: object) -> None:
        """Записать побочный эффект, который обязан был случиться."""
        self.effects.append(effect)

    def count(self) -> int:
        """Сколько эффектов случилось."""
        return len(self.effects)
