"""Нарушающая реализация: одно засеянное нарушение — дедупликации нет.

Проверка зубов обязана упасть на этом файле. Нарушение ровно одно:
повторная доставка идёт во внешнюю систему ещё раз (второй эффект).
"""


class PaymentService:
    """Приём поручений БЕЗ дедупликации по ключу (нарушение инварианта)."""

    def __init__(self, platform) -> None:
        self._platform = platform

    def process(self, key: str, amount: int) -> dict:
        """Обработать поручение; повторная доставка создаёт второй эффект."""
        return self._platform.send(key, amount)
